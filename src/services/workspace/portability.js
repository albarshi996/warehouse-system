/**
 * 🔒 حارسُ ما لا يعبر المزامنةَ التلقائيّة — ملفّاتُ النشر.
 *
 * ═══ العطب ═══
 * المستودعان يتزامنان تلقائيًّا كلّ ساعة: ورك-فلو `sync-from-sibling` يجلب من
 * الشقيق ويدمج ثمّ **يدفع بـ`GITHUB_TOKEN`**. وGitHub يرفض من رمز الأتمتة أيّ
 * دفعةٍ تُنشئ أو تُعدّل ملفَّ ورك-فلو، ولا سبيل إلى استئذانه: `workflows` ليست
 * من مفاتيح `permissions` في Actions أصلًا — فلا يُمنح إذنٌ لا وجود له.
 *
 * فتحسينٌ في `.github/workflows/` هنا **لا يبلغ الشقيق أبدًا**. وأسوأ من ذلك
 * أنّه لا يُترك وحده: الدفعةُ تُرفض كاملةً، فيسقط تشغيلُ المزامنة كلَّ ساعةٍ
 * برفضٍ من git لا يسمّي سببَه — **فينسدّ سيلُ المزامنة كلُّه**، لا ذلك الملفُّ.
 *
 * وقد وقع فعلًا: `d25b562` في مستودع الشركة (2026-08-29) رسالتُه بنصّها
 * «طُبّق بيدٍ لأنّ الأتمتة لا تملك تعديلَ ملفّات النشر».
 *
 * ═══ العلاج: الاستثناءُ لا الوقوف ═══
 * **قرارُ المالك 2026-10-02: لا شيءَ يدويّ.** فالمزامنةُ لا تقف من أجل ملفِّ
 * نشر، بل **تتجاوزه وتُكمل**: تُرجعه إلى نسخة مستودعها وتُعلن ما فعلت. فتجري
 * أبدًا بلا تدخّل، وتبقى ملفّاتُ النشر **مِلكَ كلِّ مستودعٍ لنفسه**.
 *
 * وكان الطريقُ المعتادُ أن يُمنح الدفعُ رمزًا ذا صلاحيّة `workflow`، لكنّ ذلك
 * يحتاج إضافةَ سرٍّ في مستودع الشركة — والمالكُ **ليس مديرًا عليه** (قياس
 * 2026-10-02: `admin:false`، ومالكُه حسابُ `warehouse-art`). فالبابُ مغلقٌ
 * بالصلاحيّات لا بالاختيار.
 *
 * والقاعدةُ **واحدةٌ في المستودعَين لا تتبدّل بالبيئة**، لأنّ حارسًا يقرأ حالةَ
 * البيئة يكذب في إحداهما حتمًا: يُقرأ سلوكُه هنا فيُظنّ أنّه سلوكُه هناك.
 *
 * وثمنُه مُعلَنٌ لا مكتوم: تحسينُ ورك-فلو هنا لا يبلغ الشقيق. وهو ثمنٌ صغير —
 * الملفّات متطابقةٌ اليوم، وتغيّرت مرّتين في سنة. ويُرفَع هذا الاستثناءُ كلُّه
 * متى صار للدفع رمزٌ ذو صلاحيّة `workflow`.
 */

/**
 * مجلّدُ ملفّات النشر — **في جذر المستودع لا في أيّ مجلّدٍ فرعيّ**. فـ`.github`
 * داخل `docs/` مثلًا ليست ملفّات نشرٍ عند GitHub، ولا تُمنع.
 */
export const WORKFLOW_DIR = '.github/workflows/';

/**
 * الامتدادُ الذي يعدّه GitHub ورك-فلو. وما سواه في المجلّد — `README.md` أو
 * سكربتٌ مساعد — **يعبر بلا منع**، فلا يُحسب عائقًا وإلّا كان الحارسُ كاذبًا.
 */
const WORKFLOW_EXT = /\.ya?ml$/i;

/**
 * توحيدُ شكل المسار قبل الحكم: git يُخرج بالخطّ المائل، لكنّ مصادرَ أخرى
 * (ويندوز، أو مسارٌ نُسخ بيد) قد تأتي بالخطّ العكسيّ أو ببادئة `./`.
 * والحكمُ على الشكل لا على المضمون يُخطئ صامتًا.
 */
export function normalizePath(path) {
  return String(path).replace(/\\/g, '/').replace(/^\.\//, '');
}

/** هل هذا المسارُ ملفَّ نشرٍ لا تستطيع الأتمتةُ دفعَه؟ */
export function isUnportable(path) {
  const p = normalizePath(path);
  return p.startsWith(WORKFLOW_DIR) && WORKFLOW_EXT.test(p);
}

/**
 * ملفّاتُ النشر من جملة مسارات — مرتّبةً ومنزوعةَ التكرار، فالرسالةُ تُقرأ.
 */
export function unportablePaths(paths) {
  return [...new Set((paths ?? []).map(normalizePath).filter(isUnportable))].sort();
}

/**
 * جملةُ الإعلان — تُطبع في المزامنة وفي الكومِت، فيُعرف ما استُثني ومتى.
 * والإعلانُ شرطُ القاعدة لا زينتُها: استثناءٌ صامتٌ يصير بعد شهرٍ عطبًا مجهولَ
 * السبب، فلا يُفهم لماذا افترق المستودعان.
 */
export function exclusionNote(files) {
  return files.length === 1
    ? `ملفُّ نشرٍ واحدٌ استُثني من الدمج (${files[0]}) — ملفّاتُ النشر مِلكُ كلِّ مستودعٍ لنفسه.`
    : `${files.length} ملفَّ نشرٍ استُثنيت من الدمج — ملفّاتُ النشر مِلكُ كلِّ مستودعٍ لنفسه:\n${files
        .map((f) => `  · ${f}`)
        .join('\n')}`;
}
