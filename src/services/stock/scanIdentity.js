/**
 * ═══════════════════════════════════════════════════════════════════
 *  هويّةُ الجهاز والمعرّفُ الحتميّ ‹CAP-301 · CAP-302›
 * ═══════════════════════════════════════════════════════════════════
 *
 * ═══ الفجوة (ج‑٧) ═══
 * `appendScan` كانت تكتب بـ`addDoc` — **معرّفٌ عشوائيٌّ لكلّ نداء**. فالقيدُ
 * الواحد لو أُرسل مرّتين (نقرةٌ مضاعفة · إعادةُ تحميلٍ في وسط الحفظ · محاولةٌ
 * ثانيةٌ بعد شكٍّ في الشبكة) صار **قيدَين** بكمّيّتين تُجمعان — والدفترُ
 * ملحقٌ-فقط لا يُصحَّح بحذف، فالتضاعفُ يبقى ويُصحَّح بقيدِ عكسٍ يدويّ.
 *
 * ═══ ★★ والحلّ: المعرّفُ يُحسب ولا يُولَّد ═══
 * `{op}-{device}-{seq}` — فالقيدُ نفسُه من الجهاز نفسِه له **مسارٌ واحدٌ
 * دائمًا**. وكتابتُه مرّتين تُصيب المستندَ نفسَه، فينتج **مستندٌ واحدٌ
 * وكمّيّةٌ واحدة** مهما تكرّر الإرسال.
 *
 * ═══ ★★★ ولمَ لم تُمسّ قاعدةُ `scans` ═══
 * نصُّ ‹CAP-302› يقول «إعادةُ إرسال القيد نفسه **تكتب فوق نفسها**»، وذلك
 * يقتضي `allow update` — ولو بشرطٍ ضيّق. **ولم أفعل.** لأنّ الشرط الأضيقَ
 * الممكن (`affectedKeys().hasOnly(['at'])`) يفتح بابًا لإعادة ختمِ وقتِ قيدٍ
 * قديم، ودستورُ المستودع يقول إنّ `scans` **مقدَّسة**: `update, delete: if
 * false`. وفتحُ ثقبٍ صغيرٍ في جدارٍ مقدَّسٍ ثمنٌ أغلى من المشكلة التي يحلّها.
 *
 * والنتيجةُ المطلوبةُ تتحقّق بلا ذلك الثمن: الإرسالُ الثاني على المسار نفسِه
 * **يرتدّ** (لأنّه `update` على مستندٍ قائم)، فيبقى مستندٌ واحدٌ وكمّيّةٌ
 * واحدة. الفرقُ أنّ الثاني يُرفض بدل أن يُكتب فوق الأوّل — **والمُخرَجُ
 * واحد**، وهو ما يهمّ الجردَ فعلًا. (والرفضُ يُبتلع في الشاشة: القيدُ محفوظٌ
 * أصلًا، فلا رسالةَ خطأٍ تُقلق العادّ.)
 *
 * ═══ والتسلسلُ لا يرتدّ ═══
 * عدّادٌ لكلّ جلسةٍ على الجهاز، يُزاد قبل الكتابة ويُحفظ. وإعادةُ تحميل
 * الصفحة لا تُعيده إلى الصفر — وإلّا لاصطدم القيدُ الجديد بمسار قيدٍ قديم
 * **فيُرفض صامتًا ويضيع عدٌّ حقيقيّ**. وهذا أخطر من التضاعف الذي نعالجه.
 *
 * منطق خالص: بلا Firestore وبلا DOM — التخزين يُحقن.
 */

const DEVICE_KEY = 'bzDeviceId';
const SEQ_PREFIX = 'bzScanSeq';

/** أبجديّةٌ آمنةٌ في مسارات Firestore ومقروءةٌ في السجلّ. */
const ALPHABET = 'abcdefghijklmnopqrstuvwxyz0123456789';

/**
 * هويّةُ الجهاز — **ثابتةٌ عبر إغلاق المتصفّح**، تُولَّد مرّةً وتُحفظ.
 *
 * وليست هويّةَ شخص: الشخصُ في `byUid` من Firebase Auth. هذه تجيب سؤالًا
 * آخر — «من أيّ جهازٍ جاء هذا القيد؟» — وهو ما يفصل عادَّين يتشاركان حسابًا،
 * ويجعل التسلسلَ لا يتصادم بين جهازين على الجلسة نفسها.
 *
 * ★ وتعذُّرُ التخزين لا يُعطّل شيئًا: تُولَّد هويّةٌ عابرةٌ لهذه الجلسة —
 *   فالعدُّ أَولى من الحتميّة (ق-٣).
 *
 * @param {Storage} store تخزينٌ بواجهة localStorage
 * @param {() => number} [rand]
 * @returns {string} اثنا عشر محرفًا
 */
export function deviceId(store, rand = Math.random) {
  try {
    const saved = store?.getItem?.(DEVICE_KEY);
    if (typeof saved === 'string' && /^[a-z0-9]{12}$/.test(saved)) return saved;
  } catch {
    /* تخزينٌ ممنوع — تُولَّد عابرة */
  }
  let id = '';
  for (let i = 0; i < 12; i++) id += ALPHABET[Math.floor(rand() * ALPHABET.length) % ALPHABET.length];
  try {
    store?.setItem?.(DEVICE_KEY, id);
  } catch {
    /* يُبتلع — الهويّةُ تعيش في الذاكرة لهذه الجلسة */
  }
  return id;
}

/** مفتاحُ عدّاد جلسةٍ على هذا الجهاز. */
export function seqKey(opId) {
  return `${SEQ_PREFIX}:${String(opId || '').trim()}`;
}

/**
 * ★ التسلسلُ التالي — **يُزاد ولا يرتدّ أبدًا**.
 *
 * والقيمةُ المعطوبةُ أو الناقصةُ تُقرأ صفرًا فيبدأ من ١؛ ولا يُقبل نقصانٌ:
 * عدّادٌ يعود للصفر بعد إعادة تحميلٍ يجعل القيدَ الجديد يصطدم بمسار قيدٍ
 * قديمٍ **فيُرفض ويضيع عدٌّ حقيقيّ** — وذلك أخطر من التضاعف نفسِه.
 *
 * @returns {number} رقمٌ صحيحٌ موجب
 */
export function nextSeq(store, opId) {
  const key = seqKey(opId);
  let cur = 0;
  try {
    cur = Math.trunc(Number(store?.getItem?.(key)));
  } catch {
    cur = 0;
  }
  if (!Number.isFinite(cur) || cur < 0) cur = 0;
  const next = cur + 1;
  try {
    store?.setItem?.(key, String(next));
  } catch {
    /* بلا تخزينٍ يبقى التسلسل ١ دائمًا — والمعرّفُ يبقى صالحًا وإن فقد حتميّته */
  }
  return next;
}

/**
 * ★★ معرّفُ القيد — يُحسب من الجلسة والجهاز والتسلسل، فلا عشوائيّةَ فيه.
 *
 * ويُطبَّع إلى أبجديّةٍ آمنة: مسارُ Firestore يرفض `/` ويكره النقطتين
 * المفردتين، ومعرّفُ العمليّة قد يكون رمزًا كُتب بيدٍ يومًا.
 *
 * @returns {string} `s-{op}-{device}-{seq}`
 */
export function scanDocId(opId, device, seq) {
  const clean = (v) =>
    String(v ?? '')
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]/g, '')
      .slice(0, 24);
  const n = Math.max(1, Math.trunc(Number(seq) || 1));
  return `s-${clean(opId) || 'op'}-${clean(device) || 'dev'}-${String(n).padStart(6, '0')}`;
}

/**
 * معرّفُ القيد التالي لهذا الجهاز على هذه الجلسة — نداءٌ واحدٌ يجمع الثلاثة.
 * **وله أثرٌ جانبيٌّ مقصود**: يُزيد التسلسل، فلا يُستدعى إلّا عند نيّة كتابة.
 */
export function issueScanId(store, opId, rand = Math.random) {
  const device = deviceId(store, rand);
  const seq = nextSeq(store, opId);
  return { id: scanDocId(opId, device, seq), device, seq };
}

/**
 * ★★ إثباتُ الغرض: قيودٌ بمعرّفاتٍ مكرّرة تُقرأ **قيدًا واحدًا**.
 *
 * هذه هي دالّةُ الحقيقة التي يقيس عليها الاختبار «إرسالُ القيد مرّتين يُنتج
 * كمّيّةً واحدة» — وهي أيضًا شبكةُ أمانٍ عمليّة: لو وصل الدفترُ يومًا وفيه
 * تكرارٌ (من قبل هذه المهمّة)، لم يُجمع مرّتين.
 *
 * والأوّلُ يفوز لا الأخير: المستندُ الأوّلُ هو الذي كُتب فعلًا، والثاني
 * محاولةٌ مرتدّة.
 */
export function dedupeScans(scans) {
  const seen = new Set();
  const out = [];
  for (const s of Array.isArray(scans) ? scans : []) {
    const id = String(s?.id ?? '').trim();
    if (id) {
      if (seen.has(id)) continue;
      seen.add(id);
    }
    out.push(s);
  }
  return out;
}
