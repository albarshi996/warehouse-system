/**
 * «صناديق × قطع» — إدخالُ الوعاء لصنفٍ لا وحدةَ له أصلًا (‹JR-301أ›).
 *
 * ═══ الطلب بحروف المالك ═══
 * «التخزينُ بالقطعة يكتب عددَ القطع · بشدّة الصندوق يكتب عددَ الصناديق
 * **ويضرب** في عدد القطع · ولا التخزينُ بالطبلية عددَ الصناديق ضرب عدد القطع».
 *
 * ═══ ولماذا وحدةٌ جديدة والمحرّك قائم؟ ═══
 * المسارُ القائم (`scanUomChoices` · `baseQtyPreview` · `scanEntryVerdict` في
 * `stock/scanFlow.js`) يخدم **الصنفَ الذي تُعرَف وحداته**: يعرض قائمةَ وحداته،
 * ويحوّل بمعاملٍ معرَّفٍ في بطاقته، ويرفض أيَّ وحدةٍ خارجها. وذلك صوابٌ يبقى
 * ولا يُمسّ.
 *
 * لكنّ `uomDebtReport` (في `uomWiring.js`) تقيس اليوم **١٠٤٠ صنفًا بلا وحدة
 * أساسٍ أصلًا**. ولهذه `scanUomChoices` تُرجع `[]` — فلا قائمةَ تظهر، والموظّفُ
 * الواقفُ أمام الرفّ لا يملك أن يقول «ثلاثةُ صناديقَ في كلٍّ منها اثنتا عشرة».
 * فيكتب ٣ ويقصد ٣٦، أو يكتب ٣٦ ويعدّها بيده صندوقًا صندوقًا. وفارقُ الأولى
 * ١١٠٠٪ وثمنُ الثانية وقتُه.
 *
 * ═══ فمساران، ومخرَجٌ واحد ═══
 *   · معرَّفُ الوحدة  ⇐ المسار (أ): قائمةُ وحداته ومعاملُ بطاقته. لا يمرّ هنا.
 *   · بلا وحدةٍ أصلًا ⇐ المسار (ب): يُعلن الوعاءَ ومحتواه، فيُختم المعاملُ
 *     **على القيد** لا على الصنف.
 * والحكمُ بينهما مصدَّرٌ (`needsPackEntry`) لا مظنونٌ في JSX — وهو يسأل المسارَ
 * (أ) نفسَه: «أعندك ما تعرضه؟». فلا يفترق حكمُ الشاشة عن حكم الخدمة أبدًا.
 *
 * ★★ والمعاملُ المختومُ على القيد نمطٌ قائمٌ لا اختراع: `ledger/movements.js`
 * نحو ‹١٤٦› يقرأ `uomFactor` و`uomFactorFor` ويُفضّلهما على معامل الصنف، وكذلك
 * `uomWiring.refreshLineBase` و`stampPartnerUom`. هذه تتبع النمطَ نفسَه بمصدرٍ
 * ثالث: `'declared'` — أعلنه الواقفُ أمام الرفّ لهذه الحركة وحدها.
 *
 * ⚠️ **حدٌّ لا يُتجاوز:** ولا كتابةَ في `Items_Master` من هنا. قاعدتُه للمديرين،
 * وإعلانُ موظّفٍ عن صندوقٍ فيه ١٢ قيدٌ على حركته لا تعريفٌ للصنف كلّه — فقد
 * يأتي غدًا صندوقٌ فيه ٢٤ من مورّدٍ آخر، ولو كُتب الأوّل في البطاقة لَقَلَبَ
 * حسابَ الثاني صامتًا.
 *
 * منطقٌ خالص: بلا Firestore وبلا DOM (§22 ‹995›) — والشاشةُ تعرض `entry.baseQty`
 * حين `ok` و`problem` حين لا، ولا تُعيد ضربًا ولا تبني رسالة.
 */
import { checkFraction, normalizeUom } from './uomModel.js';
import { scanUomChoices } from '../stock/scanFlow.js';

/** تقريب ٦ منازل — قاعدةُ المحرّك نفسُها، تمنع تراكم أخطاء العشريّة الثنائيّة. */
const round6 = (n) => Math.round((Number(n) || 0) * 1e6) / 1e6;

/**
 * أيحتاج هذا الصنف إدخالَ «صناديق × قطع»؟ — **الحكمُ الفاصل بين المسارين.**
 *
 * ولا يُعاد بناؤه هنا بشرطٍ يقلّد `scanUomChoices`: يُسأل المسارُ (أ) نفسُه.
 * فلو تغيّرت قاعدةُ الوحدات المتاحة غدًا تغيّر الحكمان معًا، ولا يبقى أحدُهما
 * يعرض قائمةً والآخرُ يزعم أنّها فارغة. (ولهذا يستورد `items/` من `stock/` هنا
 * خلافًا للمعتاد — الاتّجاهُ ثمنٌ مقبولٌ لمصدرِ حقيقةٍ واحد، ولا دورةَ استيرادٍ
 * فيه: `scanFlow` لا يعرف هذا الملفّ.)
 *
 * والباركودُ المجهولُ (`item === null`) في الورطة نفسِها: لا وحدةَ له كذلك،
 * فيُتاح له الوعاءُ أيضًا — وإلّا لَبقي وحدَه بلا طريقةٍ يقول بها ما عدّ.
 */
export function needsPackEntry(item) {
  return scanUomChoices(item).length === 0;
}

/**
 * حكمُ إدخال الوعاء: يفحص ويبني القيد — أو يقول **سببًا واحدًا مسمًّى**.
 *
 * ═══ ولماذا سببٌ واحدٌ لا قائمة ═══
 * `scanEntryVerdict` تُرجع `problems[]` لأنّها تفحص سياقَ التقاطٍ كاملًا (وضعٌ
 * وباركودٌ وصنفٌ واسمٌ وكمّيّة). وهذه أربعُ خاناتٍ على شاشة هاتف: من كتب صفرًا
 * في «كم في الوعاء» يصحّحه ثمّ يعيد. وأربعةُ أسطرٍ حمراءَ تحت أربع خاناتٍ ضجيجٌ
 * يُقرأ فيُهمَل — والسببُ المفرد يُقرأ فيُصلَح.
 *
 * @param {object} input
 * @param {object|null} [input.item] صنفُ الماستر — يُقرأ **للتوجيه وحده**
 * @param {string} input.containerLabel الوعاء كما سمّاه الموظّف: «صندوق» «شدّة»
 * @param {*} input.containers كم وعاءً
 * @param {*} input.perContainer كم قطعةً في الوعاء الواحد
 * @returns {{ok:boolean, problem:string,
 *            entry:{qty:number, uom:string, factor:number, baseQty:number,
 *                   factorSource:'declared', factorFor:string}|null}}
 */
export function packEntryVerdict({ item = null, containerLabel = '', containers, perContainer } = {}) {
  // ① التوجيه أوّلًا: صنفٌ تُعرَف وحداته له قائمتُه ومعاملُ بطاقته، ومعاملٌ
  // مُعلَنٌ باليد فوقهما يلتفّ على تعريفٍ قائمٍ صحيح. يُردّ إلى المسار (أ).
  if (!needsPackEntry(item)) {
    return reject('لهذا الصنف وحداتٌ معرّفة — اختر وحدته من القائمة، ولا تُعلن معاملًا فوق تعريفه.');
  }

  const spoken = String(containerLabel ?? '').trim();
  if (!spoken) {
    return reject('سمِّ الوعاء أوّلًا — صندوق أو كرتون أو شدّة أو ما تراه.');
  }

  // معرّفُ الوحدة إن عرفه سيّد الوحدات، و`''` لوعاءٍ لا يعرفه («شوال» مثلًا).
  const unitId = normalizeUom(spoken);

  const boxes = Number(containers);
  if (!Number.isFinite(boxes) || boxes <= 0) {
    return reject(`كم ${spoken}؟ — رقمٌ أكبر من صفر.`);
  }
  // ⚠️ حارسُ الكسر بالنواة (`checkFraction`) لا بحكمٍ محلّيّ. ومزلقُه أنّه
  // **يتساهل مع المجهول**: `allowsFraction` تُرجع `true` لعائلةٍ فارغة، فوعاءٌ
  // اسمُه «شوال» يمرّ بنصفه. والوعاءُ يُعدّ عدًّا مهما سُمّي — فالمجهولُ يُحكَّم
  // بـ`piece` أساسِ عائلة العدّ، وتُسمّى في رسالته الكلمةُ التي كتبها الموظّف.
  const boxesCheck = checkFraction(boxes, unitId || 'piece');
  if (!boxesCheck.ok) {
    return reject(unitId ? boxesCheck.problem : `«${spoken}» تُعدّ عدًّا — ${boxes} ليست عددَ أوعيةٍ صحيحًا.`);
  }

  // ③ صفرٌ أو فراغٌ يُرفض **بسببٍ مسمًّى**: `Number('')` صفرٌ محدود، فلو مرّ
  // لَحُسب مجموعٌ صفرٌ من جهل — وصفرٌ صامتٌ أخطر من امتناعٍ معلَن.
  const inner = Number(perContainer);
  if (!Number.isFinite(inner) || inner <= 0) {
    return reject(`كم قطعةً في ${spoken} الواحد؟ — صفرٌ أو فراغٌ لا يُحسب منه مجموع.`);
  }
  // ومحتوى الوعاء قِطَعٌ بنصّ المالك («ويضرب في عدد القطع») — والقطعةُ لا تتجزّأ.
  const innerCheck = checkFraction(inner, 'piece');
  if (!innerCheck.ok) return reject(innerCheck.problem);

  return {
    ok: true,
    problem: '',
    entry: {
      qty: boxes,
      // ★★ الوعاءُ يُختم **كما نطقه الموظّف** لا مُطبَّعًا: هذا الصنف لا وحدةَ
      // أساسٍ له، وأكثرُ أوعيته لا معرّفَ لها في سيّد الوحدات — فتطبيعُ نصفها
      // وتركُ نصفها يُنتج حقلًا بقاعدتين. والمعرّفُ القياسيُّ يذهب إلى
      // `factorFor` وحده: نصٌّ للإنسان ومعرّفٌ للآلة، وهو عينُ ما يقارنه
      // `movements.js` (`stampedFor === (normalizeUom(entryUom) || entryUom)`).
      uom: spoken,
      factor: inner,
      baseQty: round6(boxes * inner),
      // مصدرٌ ثالثٌ إلى جانب `'item'` و`'partner'`: أعلنه العادُّ لهذه الحركة.
      // ⚠️ وهو **مقروءٌ في مسار المسح** (`scanBaseQty` تقرأ `baseQty` المختومة)،
      // أمّا `movements.js` فلا يُفضّل اليوم إلّا `'partner'` — فإن سِيقت هذه
      // القيود يومًا إلى سطر مستندٍ وجب توسيعُ ذلك الشرط هناك أوّلًا.
      factorSource: 'declared',
      factorFor: unitId || spoken,
    },
  };
}

/** رفضٌ بسببه — شكلُ المخرَج واحدٌ في الحالين، فلا تفحص الشاشةُ وجودَ الحقل. */
function reject(problem) {
  return { ok: false, problem, entry: null };
}
