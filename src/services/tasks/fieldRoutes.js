/**
 * المسارات الميدانيّة — من صفّ المستند إلى الشاشة التي تنفّذه. منطقٌ خالص.
 *
 * ═══ الفجوة التي يسدّها ═══
 * صفحةُ المستندات لا تحمل رابطًا واحدًا إلى شاشةٍ ميدانيّة. فالمديرُ يعتمد
 * أمرَ شراءٍ، والموظّفُ يجب أن **يعرف بنفسه** أن يفتح تطبيقًا آخر ويبحث فيه
 * عن أمره. والمعرفةُ الشفويّة أوّلُ ما يسقط عند تبديل الورديّة.
 *
 * ═══ ★★★ والخريطةُ تُشتقّ ولا تُخترع ═══
 * كلُّ نوعٍ هنا **مقيسٌ من حارسٍ قائم** لا من ظنّ:
 *   · `PICK` و`SO` من `PICKABLE_TYPES` في `lpn/pickingTask.js` — بوّابةُ شاشة
 *     التحضير نفسُها. فلو قبِلت نوعًا رابعًا غدًا ظهر له الزرُّ بلا تعديلٍ هنا.
 *   · `PUTAWAY` من `DOC_WORK_TYPE` في `tasks/taskFactory.js` — النوعُ الذي
 *     يولّد عملَ تخزينٍ هو النوعُ الذي يفتح لوحةَ الخانة.
 *   · `PO` و`TR` مرآةٌ لبوّابة `sessionOpenProblem` في `lpn/receivingSession.js`.
 *     ⚠️ **مرآةٌ لا استيراد**: الملفُّ يفحص النوعين بنصّهما ولا يصدّر ثابتًا
 *     يُستورَد. فالمرآةُ تنحرف صامتةً — ولذلك يقيسها اختبارٌ **سلوكيًّا**:
 *     يمرّر كلَّ نوعٍ موجَّهٍ إلى الاستلام على البوّابة ويطالبها بقبوله.
 *   · `CC` محضرُ الجرد الدوريّ — النوعُ الوحيد في `COUNT_CHAIN` الذي يُعدّ
 *     عليه (والتسويةُ `ADJ` تأتي بعده لا قبله)، ويحرسه اختبارُ «كلُّ نوعٍ
 *     موجَّهٍ نوعُ مستندٍ حقيقيّ في `chain.js`».
 *
 * ═══ ★★★ ولماذا يسكن `tasks/` لا `documents/` ═══
 * كُتب أوّلًا في `services/documents/` — وهو موضعُه الطبيعيُّ بالاسم — فأسقط
 * حارسَ العزل `lpnIsolation.test.js`: **`ledger` و`balances` و`documents` نوًى
 * محميّةٌ لا تستورد من `lpn` أبدًا** (ح-٢)، كي لا يصير الدفترُ القائمُ معتمِدًا
 * على الطبقة الأحدث فيُتلفَه عطبُها. وهذه الوحدةُ تستورد `PICKABLE_TYPES` من
 * `lpn/pickingTask.js` **بالضرورة** — فهي جسرٌ يعرف الطرفين، وجسرٌ لا يسكن
 * داخل النواة التي يحرسها الحارس. و`tasks/` موضعُه: هناك `taskFactory.js`
 * يقيس أصلًا «أيَّ عملٍ يولّده هذا المستند»، وهذا يقيس «وأيُّ شاشةٍ تنفّذه».
 * فمن أعاده إلى `documents/` أسقط البناءَ — والحارسُ يقول له لماذا.
 *
 * ═══ ثلاثةُ شروطٍ حاكمة ═══
 * ① **الحالةُ شرطٌ كالنوع.** `canDeriveFrom` — معتمَدٌ أو منجَز لا غير. فلا
 *    يُدعى أحدٌ إلى تنفيذ مسوّدةٍ لم تُعتمد، وهو عرفُ محرّك المستندات نفسِه:
 *    ما لا يُشتقّ منه مستندٌ لا يُشتقّ منه عمل. والمرفوضُ يُعيد `null` **لا
 *    زرًّا معطَّلًا**: الزرُّ الرماديُّ يَعِد بشيءٍ ثمّ يمنعه، وغيابُه أصدق.
 * ② **المجهولُ `null`.** نوعٌ لا شاشةَ له لا يُخترع له زرٌّ ميّت.
 * ③ **و`reason` يُعرض في `title=`** — فيعرف من يقف على الزرّ ما ينتظره خلفه
 *    قبل أن يضغط، لا بعد أن تنفتح شاشةٌ لا يفهم لماذا فُتحت.
 *
 * ═══ ⚠️ ومزلقان مكتوبان ═══
 * **الأوّل: المسارُ بلا معرّف المستند.** قُرئت الشاشاتُ الأربع فلم تقرأ
 * واحدةٌ منها `searchParams` — فرابطٌ بـ`?doc=PO-1023` يُهمَل صامتًا ويظنّ
 * الموظّفُ أنّ الشاشة فتحت على أمره وهي على قائمتها. فالمسارُ عارٍ حتّى
 * تقرأه الشاشة، ثمّ يُضاف هنا وفي الشاشة معًا لا هنا وحده.
 *
 * **والثاني: الزرُّ لا يعرف أيَّ طرفٍ يقف أمامه.** `TR` طلبُ نقلٍ له طرفان:
 * المُرسِلُ يحضّره والمستقبِلُ يستلمه — و`PICKABLE_TYPES` تعدّه قابلًا
 * للتحضير و`sessionOpenProblem` يقبله للاستلام، وكلاهما صادق. فحُسم
 * **للاستلام** (انظر `RECEIVABLE_TYPES` أدناه)، والتمييزُ الحقيقيُّ يحتاج
 * مستودعَ المستخدم مقابل `header.fromWarehouse` — وهو **غيرُ ممرَّرٍ عمدًا**:
 * الدالّةُ تأخذ المستند وحده، فلو أخذت المستخدمَ لصارت حارسَ صلاحيّاتٍ ثانيًا
 * بجانب `pageAccess.js` — والحارسُ المزدوج ينحرف.
 */

import { DOC_WORK_TYPE } from './taskFactory.js';
import { PICKABLE_TYPES } from '../lpn/pickingTask.js';
import { canDeriveFrom } from '../documents/states.js';

const up = (v) => String(v ?? '').trim().toUpperCase();

/* ═══════════════ الوجهاتُ الأربع ═══════════════ */

const RECEIVING = Object.freeze({
  path: '/dashboard/lpn-receiving',
  label: 'ابدأ الاستلام الميدانيّ',
  reason: 'يفتح جلسةَ استلامٍ على الرصيد المفتوح لهذا الأمر: تُمسح البضاعةُ عند الشاحنة فتُبنى طبالي، ولا يُستلم صنفٌ خارجه.',
});

const PICKING = Object.freeze({
  path: '/dashboard/lpn-picking',
  label: 'ابدأ التحضير الميدانيّ',
  reason: 'يفتح مهمّةَ تحضيرٍ بمسار مشيٍ مرتَّب: من أيّ رفٍّ يُسحب كلُّ بندٍ وبأيّ ترتيب — بترتيب FEFO لا بالاجتهاد.',
});

const COUNTING = Object.freeze({
  path: '/dashboard/lpn-count',
  label: 'ابدأ جرد الطبالي',
  reason: 'يشهد للحمولة المغلقة بمسحةٍ واحدة بدل عدّ الكراتين واحدةً واحدة — شهادةُ رؤيةٍ لا احتسابُ كمّيّة.',
});

const BIN_CONSOLE = Object.freeze({
  path: '/dashboard/bin-console',
  label: 'افتح لوحة الخانة',
  reason: 'تُمسح الخانةُ فتنفتح بما فيها، ويُنفَّذ عليها هذا الأمرُ بمرجع استلامه — فالتخزينُ تنفيذُ أمرٍ لا اختراعُه.',
});

/**
 * الأنواعُ التي يُستلَم عليها ميدانيًّا.
 *
 * ⚠️ مرآةُ `sessionOpenProblem` (`lpn/receivingSession.js`) — تُحدَّث معها،
 * ويقيس تطابقَهما اختبارٌ سلوكيّ لا نصّيّ.
 *
 * ★★ وهي **تسبق** `PICKABLE_TYPES` عند التداخل: `TR` في القائمتين، وطلبُ
 * النقل عند من يقف على صفّه اليوم واردٌ يُستلَم. أمّا عملُ الطرف المُرسِل
 * فيقع على مذكّرة الشحن `TRN` — ولا شاشةَ لها بعد (انظر `OMITTED_TYPES`).
 */
const RECEIVABLE_TYPES = Object.freeze(['PO', 'TR']);

/** أنواعُ المستندات التي تولّد عملَ تخزين — مقيسةٌ من مصنع المهامّ لا مكرّرة. */
const PUTAWAY_TYPES = Object.freeze(
  Object.keys(DOC_WORK_TYPE).filter((t) => DOC_WORK_TYPE[t] === 'putaway')
);

/**
 * الخريطةُ المجمَّدة — يقرؤها الحارسُ كما تقرؤها الشاشة، فلا نسختان.
 *
 * تُبنى بالاشتقاق لا بالسرد: التحضيرُ كلُّ ما تقبله بوّابتُه ناقصًا ما
 * ادّعاه الاستلامُ أوّلًا، والتخزينُ ما يولّد عملَ تخزين.
 */
export const FIELD_ROUTES = Object.freeze({
  ...Object.fromEntries(RECEIVABLE_TYPES.map((t) => [t, RECEIVING])),
  ...Object.fromEntries(
    PICKABLE_TYPES.filter((t) => !RECEIVABLE_TYPES.includes(t)).map((t) => [t, PICKING])
  ),
  CC: COUNTING,
  ...Object.fromEntries(PUTAWAY_TYPES.map((t) => [t, BIN_CONSOLE])),
});

/**
 * الغيابُ المقصودُ مكتوبًا — **لا صمت**.
 *
 * نوعٌ يعرفه حارسٌ ميدانيٌّ ولا مسارَ له يجب أن يُعلن سببَه هنا، وإلّا سقط
 * الاختبار. فالفرقُ بين «قرّرنا ألّا نوجّهه» و«نسيناه» هو هذا الجدول.
 */
export const OMITTED_TYPES = Object.freeze({
  TRN: 'مذكّرةُ الشحن تولّد عملَ نقلٍ داخليّ ولا شاشةَ ميدانيّةً له بعد — عملُها يُسنَد مهمّةً في «/dashboard/tasks». ولو وُجّهت إلى الاستلام لَرفضتها بوّابتُه (ليست PO ولا TR) فوقف الموظّفُ أمام شاشةٍ تردّه.',
});

/**
 * الشاشةُ الميدانيّة لهذا المستند — أو `null`.
 *
 * @param {{type?:string, state?:string}|null|undefined} doc المستند كما هو في صفّ القائمة
 * @returns {{path:string, label:string, reason:string}|null}
 */
export function fieldRouteFor(doc) {
  const route = FIELD_ROUTES[up(doc?.type)];
  if (!route) return null; // ② المجهولُ لا زرَّ له

  // ① الحالةُ شرطٌ كالنوع. والحالاتُ معرّفاتٌ صغيرةٌ في `STATES` فلا تُخفَّض
  // هنا: التخفيضُ يقبل «Approved» وهي حالةٌ لا وجودَ لها في الجدول، فيُخفي
  // عطبَ كتابةٍ في المستند بدل أن يكشفه.
  if (!canDeriveFrom(String(doc?.state ?? '').trim())) return null;

  // نسخةٌ لا الكائنَ المجمَّد: الشاشةُ قد تُثري ما تعرضه، ولا تُفسد الجدول.
  return { path: route.path, label: route.label, reason: route.reason };
}
