/** خطأُ «موجودٌ سلفًا» على كتابة إنشاءٍ بمعرّفٍ عشوائيّ ⟵ كتابتُنا نفسُها أُعيدت، فهي نجاح. */
export function isOwnRetriedCreate(err) {
  return String(err?.code || '').replace(/^firestore\//, '') === 'already-exists';
}
