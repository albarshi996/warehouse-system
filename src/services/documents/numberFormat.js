/**
 * صيغة الرقم الرسمي — منطق خالص بلا شبكة ولا Firebase.
 *
 * مفصول عن `numberingService.js` عمدًا: صيغة الرقم هي العقد الذي يراه المدقّق على
 * الورق، فيجب أن تُختبر وحدها دون الحاجة إلى سحابة ولا متصفّح.
 *
 * الصيغة المعتمدة (قرار المالك 2026-07-15): `GRN-2026-0001`
 *   النوع · السنة · تسلسل من أربع خانات يبدأ من 0001 ويُصفَّر مع كل سنة.
 */

/** عدد خانات التسلسل. */
export const SEQ_PAD = 4;

/** معرّف عدّاد النوع في سنة بعينها: `GRN-2026`. */
export function counterId(type, year) {
  return `${type}-${year}`;
}

/** يبني الرقم الرسمي: ('GRN', 2026, 1) ⇒ 'GRN-2026-0001' */
export function formatNumber(type, year, seq) {
  return `${type}-${year}-${String(seq).padStart(SEQ_PAD, '0')}`;
}

/**
 * قاعدة الزيادة: التسلسل التالي من العدّاد الحاليّ.
 *
 * نُقلت من طبقة التخزين إلى هنا (EXE-002): **القاعدة في الكود والقاعدة مخزنٌ
 * لا حاكم.** والزيادة قاعدةُ عملٍ لا تفصيلَ شبكة — عدّادٌ مفقود أو تالف يبدأ
 * من 1 ولا يتوقّف، وعدّادٌ سالبٌ أو نصٌّ لا يُنتج رقمًا سالبًا يكسر التدقيق.
 */
export function nextSeq(current) {
  const n = Number(current);
  return (Number.isFinite(n) && n > 0 ? Math.floor(n) : 0) + 1;
}

/** يفكّ الرقم إلى أجزائه، أو null إن لم يطابق الصيغة. */
export function parseNumber(number) {
  const m = /^([A-Z]+)-(\d{4})-(\d+)$/.exec(String(number || ''));
  if (!m) return null;
  return { type: m[1], year: Number(m[2]), seq: Number(m[3]) };
}

/**
 * ═══ ★★★ حارسُ الترقيم بلا اتّصال ‹NUM-601› ═══
 *
 * كان رأسُ `numberingService` يقول منذ البداية «⚠️ لا يعمل بلا إنترنت» —
 * **ولم يكن في الكود ما يُلزِم ذلك**. فالتعليقُ وصفٌ والواقعُ أسوأُ منه:
 * `runTransaction` بلا اتّصالٍ **لا يفشل بل يتعلّق أبدًا** (بخلاف `setDoc`
 * التي تُقيَّد في طابور الأوفلاين وتعود فورًا). فوعدُ الحجز لا يُحسَم، ومعالجُ
 * الزرّ ينتظر إلى غير نهاية: لا رسالةَ نجاحٍ ولا خطأ — **والزرُّ يبقى معطّلًا
 * على «تُثبَّت…»**.
 *
 * وهو ما رآه المالكُ حرفيًّا 2026-10-21: عشرُ بطاقاتِ صرفٍ في يومٍ واحد
 * كلُّها «مسودّة · بلا رقم»، والمسودّاتُ تُحفظ لأنّها `setDoc`. فظهر النظامُ
 * وكأنّه يبتلع العمل. ويشمل العطبُ **تسعَ خدماتٍ** تحجز أرقامَها من هنا
 * (المستندات · العُهد · الأسطول · الطبالي · الصيانة · الاجتماعات بنوعيها ·
 * المركبات · بطاقات فينسيا).
 *
 * ★★ **و`navigator.onLine === false` وحدَها يُوثق بها**: نفيُها قاطعٌ
 * (المتصفّحُ لا يقول «غير متصل» وهو متصل)، وإثباتُها ظنٌّ (جهازٌ على راوترٍ
 * بلا إنترنت يقول «متصل»). فيُمنع الحجزُ عند النفي القاطع وحدَه، ولا يُمنع
 * عند الظنّ — فحارسٌ يمنع عملًا صحيحًا أسوأُ من حارسٍ يسكت.
 */
export const OFFLINE_NUMBER_MESSAGE =
  'التثبيتُ يحتاج اتّصالًا بالإنترنت — فالرقمُ الرسميُّ لا يُحجز محلّيًّا. ' +
  'ومسودّتُك محفوظةٌ ولم تضع: ثبّتها حين تعود الشبكة.';

/**
 * هل يجوز حجزُ رقمٍ الآن؟ — حكمٌ خالصٌ يأخذ حالةَ الاتّصال ولا يقرؤها بنفسه،
 * فيُختبر في Node بلا متصفّح.
 *
 * @param {{online?: boolean}} [state] `false` تعني «غير متّصلٍ يقينًا»
 * @returns {{ok: boolean, code: string, message: string}}
 */
export function numberingVerdict({ online } = {}) {
  return online === false
    ? { ok: false, code: 'offline', message: OFFLINE_NUMBER_MESSAGE }
    : { ok: true, code: '', message: '' };
}
