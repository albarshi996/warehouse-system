--  ٠١٣ — المرآةُ العامّة: «كلُّ ما يُحفظ في قوقل موجودٌ في سيرفر الجهاز»
-- ═══════════════════════════════════════════════════════════════════════════
--
--  ★★★ **أمرُ المالك 2026-10-20 حرفيًّا:** «أيُّ شيءٍ يُحفظ في قوقل موجودٌ في
--      سيرفر الجهاز، والقراءةُ تكون في سيرفر الجهاز». والمرآةُ يومَها **خمسُ
--      مجموعاتٍ من ثمانٍ وتسعين**.
--
--  **ولماذا جدولٌ عامٌّ بدل تسعةٍ وثمانين جدولًا مفصَّلًا:**
--
--    بناءُ مخطَّطٍ لكلّ مجموعةٍ يعني تسعةً وثمانين قرارَ أعمدةٍ وقيودٍ وخريطةِ
--    حقول — شهورًا، وكلُّ شهرٍ تُضاف فيه مجموعةٌ جديدةٌ يعود النقصُ من أوّله.
--    **والهدفُ ليس نمذجةَ كلّ شيء، بل ألّا يبقى شيءٌ خارجَ الجهاز.** فالجدولُ
--    العامُّ يبلغ الهدفَ في خطوةٍ واحدةٍ ولا يشيخ: مجموعةٌ تُضاف غدًا تُنسخ
--    يومَ تُضاف بلا سطرِ كود.
--
--  ★★ **ولا يُلغي الجداولَ المفصَّلة ولا يُنافسها.** `items` و`documents`
--     تبقيان، لأنّ فيهما ما لا يعطيه `jsonb`: **قيدُ تفرّد رقم المستند**
--     و**تفرّدُ الباركود** — وهما اللذان أمسكا ثمانيةَ عشرَ مستندًا مكرَّرًا
--     وصنفين، وهو عطبٌ حيٌّ لا حارسَ له في Firestore. ⇒ فالنواةُ منمذَجةٌ
--     لأنّها تُحرَس، وما سواها محفوظٌ لأنّه يُحفظ.
--
--  ⚠️ **وحدٌّ معلَنٌ لا يُخفى:** مستندٌ يُحذف من Firestore **يبقى هنا**.
--     فالمزامنةُ تقرأ ما تغيّر ولا ترى ما اختفى. والمسارُ الكاملُ (`full`)
--     يمكن أن يكشفه مستقبلًا بمقارنة المجموعة كلِّها؛ والتدريجيُّ لا يستطيع
--     بنيويًّا. ولا يُدَّعى غيرُ ذلك.
-- ═══════════════════════════════════════════════════════════════════════════

CREATE TABLE IF NOT EXISTS mirror_docs (
  -- مسارُ المجموعة في Firestore كما تكتبه القواعد (`assets` · `recipes` …).
  path        text        NOT NULL,
  -- معرّفُ المستند كما هو هناك — فلا ترجمةَ ولا اختراعَ مفتاح.
  doc_id      text        NOT NULL,
  -- المستندُ كاملًا. و`buildUpsert` يصبّ فيه كلَّ ما لم يُستهلَك.
  data        jsonb       NOT NULL DEFAULT '{}'::jsonb,
  -- ختمُ التعديل المقروءُ من المستند نفسِه إن حمله — وإلّا `NULL` بصدق.
  updated_at  timestamptz,
  -- متى لمسته المزامنةُ آخرَ مرّة. ويُحدَّث في كلّ كتابةٍ فعليّة.
  synced_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (path, doc_id)
);

-- ★ فهرسٌ على المسار وحدَه: كلُّ قراءةٍ من البوّابة تبدأ بـ`path = …`، والمفتاحُ
--   المركّبُ يخدمها، لكنّ الترتيبَ بالختم داخل مسارٍ واحدٍ هو النمطُ الغالب.
CREATE INDEX IF NOT EXISTS mirror_docs_path_updated
  ON mirror_docs (path, updated_at DESC NULLS LAST);

-- ═══ الصلاحيّة ═══
--
-- ★★★ ويُمنح `web_user` **القراءةَ وحدَها**. ولا سياسةَ كتابةٍ البتّة: المزامنةُ
--     تكتب بدور مالك الجدول فتتجاوز RLS، **والبوّابةُ لا تملك طريقًا للكتابة
--     هنا أصلًا** — وهذا يحفظ القاعدةَ الحاكمة: مصدرُ الحقيقة واحدٌ، وهو
--     Firebase، وهذه مرآتُه لا نسخةٌ ثانيةٌ تُنافسه.
ALTER TABLE mirror_docs ENABLE ROW LEVEL SECURITY;
ALTER TABLE mirror_docs FORCE ROW LEVEL SECURITY;

GRANT SELECT ON mirror_docs TO web_user;

DROP POLICY IF EXISTS mirror_docs_read_signed_in ON mirror_docs;
CREATE POLICY mirror_docs_read_signed_in ON mirror_docs
  FOR SELECT TO web_user
  USING (signed_in());

-- ───────────────────────────────────────────────────────────────────────────
--  ★★★ حارسٌ يُطلَق الآن: لا يقرأ المجهولُ ولا دورُ الاتّصال حرفًا.
--  (ونفسُ حارس `008-postgrest.sql`، يُعاد على الجدول الجديد — فجدولٌ يُضاف
--   بلا هذا الفحص هو البابُ الذي يُنسى.)
-- ───────────────────────────────────────────────────────────────────────────
DO $$
BEGIN
  IF has_table_privilege('web_anon', 'mirror_docs', 'SELECT')
     OR has_table_privilege('authenticator', 'mirror_docs', 'SELECT') THEN
    RAISE EXCEPTION 'تسريبُ صلاحيّة: mirror_docs مقروءةٌ لدورٍ لا يجوز له ذلك.';
  END IF;
  IF has_table_privilege('web_user', 'mirror_docs', 'INSERT')
     OR has_table_privilege('web_user', 'mirror_docs', 'UPDATE')
     OR has_table_privilege('web_user', 'mirror_docs', 'DELETE') THEN
    RAISE EXCEPTION 'المرآةُ تُقرأ ولا تُكتب من البوّابة — صلاحيّةُ كتابةٍ ممنوحةٌ خطأً.';
  END IF;
  RAISE NOTICE 'mirror_docs: قراءةٌ لمن دخل، ولا كتابةَ لأحدٍ من البوّابة.';
END $$;

INSERT INTO schema_migrations (version) VALUES ('013-mirror-docs')
