--  م١ · متجرُ المستندات العامّ — طبقةُ التخزين المحلّيّة على هيئة Firestore
-- ═══════════════════════════════════════════════════════════════════════════
--
-- ★★★ لماذا متجرٌ عامٌّ لا جداولُ `db/schema` الاثنان والعشرون الآن؟
--     لأنّ المحوَّل `local-sqlite` يُصدّر عقدَ Firestore (مجموعة/وثيقة JSON)،
--     فمتجرٌ (مجموعة + معرّف) ⟵ JSON يُشغّل العقدَ كلَّه بلا ربطٍ لكلّ مجموعةٍ
--     على حدة. والجداولُ العلائقيّة (الأصناف · المستندات · المحاسبة …) تُرحَّل
--     في م٢ حين تُوصَل كلُّ دورةٍ بشكلها (كما يفعل `pgShape` للمرآة)، لا قبل.
--
-- ★★ الوقتُ يُخزَّن ISO داخل الـJSON موسومًا `{"__ts__": "..."}` فيعود
--    Timestamp عند القراءة، و`COALESCE(json_extract(data,'$.f.__ts__'),
--    json_extract(data,'$.f'))` يجعل الترتيبَ والترشيحَ يعملان على النوعين.

CREATE TABLE IF NOT EXISTS kv_docs (
  collection TEXT NOT NULL,          -- مسارُ المجموعة (قد يكون متفرّعًا: a/b/c)
  id         TEXT NOT NULL,          -- معرّفُ الوثيقة داخل المجموعة
  data       TEXT NOT NULL,          -- الوثيقةُ كاملةً JSON
  updated_at TEXT NOT NULL,          -- ISO آخر كتابة
  PRIMARY KEY (collection, id)
);

CREATE INDEX IF NOT EXISTS idx_kv_docs_collection ON kv_docs (collection);
